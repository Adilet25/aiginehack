    spaceCtx.fillStyle = "#4a85b8";
    spaceCtx.beginPath();
    spaceCtx.arc(earthX, earthY, earthR, 0, Math.PI * 2);
    spaceCtx.fill();
    spaceCtx.fillStyle = "#0c1528";
    spaceCtx.beginPath();
    spaceCtx.arc(earthX, earthY, earthR, -Math.PI / 2, Math.PI / 2);
