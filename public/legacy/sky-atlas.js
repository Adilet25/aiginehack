    spaceCtx.fillRect(0, 0, w, h);

    spaceStars.forEach((s) => {
      spaceCtx.fillStyle = `rgba(217, 235, 255, ${s.a})`;
      spaceCtx.beginPath();
      spaceCtx.arc(s.x * w, s.y * h, s.r, 0, Math.PI * 2);
      spaceCtx.fill();
    });

    if (sim.togoolFlashAlpha > 0) {
      spaceCtx.fillStyle = `rgba(240, 179, 90, ${sim.togoolFlashAlpha * 0.2})`;
      spaceCtx.fillRect(0, 0, w, h);
    }

    // Солнце слева (направление от Земли на Солнце = угол Math.PI)
    const sunX = -w * 0.05;
    const sunY = h * 0.52;
    const sunR = Math.min(w, h) * 0.15;
    const sunGlow = spaceCtx.createRadialGradient(
      sunX,
      sunY,
      sunR * 0.5,
      sunX,
      sunY,
      sunR * 3,
    );
    sunGlow.addColorStop(0, "rgba(255, 223, 170, 0.85)");
    sunGlow.addColorStop(0.3, "rgba(240, 179, 90, 0.25)");
    sunGlow.addColorStop(1, "rgba(240, 179, 90, 0)");
    spaceCtx.fillStyle = sunGlow;
    spaceCtx.beginPath();
    spaceCtx.arc(sunX, sunY, sunR * 3, 0, Math.PI * 2);
    spaceCtx.fill();

    spaceCtx.fillStyle = "#ffdfaa";
    spaceCtx.beginPath();
    spaceCtx.arc(sunX, sunY, sunR, 0, Math.PI * 2);
    spaceCtx.fill();
    spaceCtx.fillStyle = "#f8eed9";
    spaceCtx.font = '700 10.5px "PT Sans", sans-serif';
    spaceCtx.fillText(t.sunLabel, 10, sunY - sunR - 10);

    const earthX = w * 0.56;
    const earthY = h * 0.52;
    const orbitR = Math.min(w * 0.3, h * 0.33);

    const curLun = getActiveSimLunation();
    // Против часовой стрелки на экране (в Canvas Y вниз, поэтому вычитаем угол)
    const urkorSynodic = (curLun.N / LUNAR_CYCLE) * Math.PI * 2;
    const urkorAngle = Math.PI - urkorSynodic;
    const moonSynodic = (sim.day / LUNAR_CYCLE) * Math.PI * 2;
    const moonAngle = Math.PI - moonSynodic;
    const isTogoolNow = Math.abs(sim.day - curLun.N) < 0.3;

    // Сектор невидимости Үркөр в лучах Солнца (±20°)
    spaceCtx.save();
    spaceCtx.fillStyle = "rgba(244, 198, 77, 0.08)";
    spaceCtx.beginPath();
    spaceCtx.moveTo(earthX, earthY);
    spaceCtx.arc(
      earthX,
      earthY,
      orbitR * 1.28,
      Math.PI - 20 * DEG,
      Math.PI + 20 * DEG,
    );
    spaceCtx.closePath();
    spaceCtx.fill();
    spaceCtx.restore();

    // Базовая орбита Луны
    spaceCtx.strokeStyle = "rgba(164, 186, 213, 0.22)";
    spaceCtx.lineWidth = 1.2;
    spaceCtx.setLineDash([4, 5]);
    spaceCtx.beginPath();
    spaceCtx.arc(earthX, earthY, orbitR, 0, Math.PI * 2);
    spaceCtx.stroke();
    spaceCtx.setLineDash([]);

