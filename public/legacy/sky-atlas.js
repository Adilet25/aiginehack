function computeLunation(k) {
  let d = 5.26 + LUNAR_CYCLE * k;
  for (let i = 0; i < 5; i++) d -= wrap180(moonLon(d) - sunLon(d)) / 12.19;
  const s = sunLon(d);
  const p = pleiadesLon(d);
  const ang = mod360(p - s);
  let t = d + ang / 13.18;
  for (let i = 0; i < 6; i++) t -= wrap180(moonLon(t) - p) / 13.18;
  const N = t - d;
  const dists = MONTHS_DATA.map((m) => {
    const diff = Math.abs(N - m.togoAstro);
    return Math.min(diff, 29.53 - diff);
  });
  return { k, d, t, N, s, p, ang, ix: dists.indexOf(Math.min(...dists)) };
}

function getYearLunations(year) {
  const a = toJ2000(Date.UTC(year, 0, 1));
  const b = toJ2000(Date.UTC(year + 1, 0, 1));
  const k0 = Math.floor((a - 5.26) / LUNAR_CYCLE);
  const list = [];
  for (let k = k0; k < k0 + 14; k++) {
    const item = computeLunation(k);
    if (item.d >= a - 0.25 && item.d < b - 0.25) list.push(item);
  }
  return list;
}

