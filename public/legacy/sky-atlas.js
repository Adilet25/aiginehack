  /* Непрерывная небесная дуга от Запада (0°, закат) через Полночь (180°) к Востоку (360°, рассвет):
     Луна за 29.5 суток плавно проходит слева направо без скачков назад */
  function skyDomePoint(elongDeg, w, h) {
    const e = mod360(elongDeg);
    const u = e / 360; // строго от 0 (Запад) до 1 (Восток)
    const leftX = w * 0.1;
    const rightX = w * 0.9;
    const baseY = h * 0.72;
    const peakY = h * 0.21;
    const x = leftX + (rightX - leftX) * u;
    const y = baseY - Math.sin(u * Math.PI) * (baseY - peakY);
    return { x, y, u, elong: e };
  }

  /* Физически точная фаза Луны для северного полушария (Бишкек):
     0..0.5 (растущая) — освещена правая сторона (к закату);
     0.5..1.0 (убывающая) — освещена левая сторона (к рассвету) */
  function drawSkyMoon(ctx, cx, cy, r, phaseNorm, isTogoolNow) {
    const p = ((phaseNorm % 1) + 1) % 1;
    const illumination = 0.5 * (1 - Math.cos(p * Math.PI * 2));

    if (illumination > 0.03) {
      const glow = ctx.createRadialGradient(
        cx,
        cy,
        r * 0.75,
        cx,
        cy,
        r * (1.8 + illumination * 1.4),
      );
      glow.addColorStop(0, `rgba(255, 223, 170, ${0.26 * illumination})`);
      glow.addColorStop(1, "rgba(255, 223, 170, 0)");
      ctx.fillStyle = glow;
      ctx.beginPath();
      ctx.arc(cx, cy, r * (1.8 + illumination * 1.4), 0, Math.PI * 2);
      ctx.fill();
    }

    // Тёмный диск (пепельный свет)
    ctx.fillStyle = "rgba(12, 21, 40, 0.92)";
    ctx.beginPath();
    ctx.arc(cx, cy, r, 0, Math.PI * 2);
    ctx.fill();

    ctx.strokeStyle = isTogoolNow
      ? "rgba(240, 179, 90, 0.95)"
      : "rgba(164, 186, 213, 0.38)";
    ctx.lineWidth = isTogoolNow ? 2 : 1;
    ctx.beginPath();
    ctx.arc(cx, cy, r, 0, Math.PI * 2);
    ctx.stroke();

    if (illumination < 0.015) return;

    const isWaxing = p <= 0.5;
    const k = Math.cos(p * Math.PI * 2);
    // Лёгкий естественный наклон оси серпа к горизонту
    const tilt = isWaxing ? -0.22 : 0.22;

    ctx.save();
    ctx.translate(cx, cy);
    ctx.rotate(tilt);

    ctx.beginPath();
    if (isWaxing) {
      ctx.arc(0, 0, r, -Math.PI / 2, Math.PI / 2, false);
      ctx.ellipse(
        0,
        0,
        r * Math.abs(k),
        r,
        0,
        Math.PI / 2,
        -Math.PI / 2,
        k > 0,
      );
    } else {
      ctx.arc(0, 0, r, Math.PI / 2, (Math.PI * 3) / 2, false);
      ctx.ellipse(
        0,
        0,
        r * Math.abs(k),
        r,
        0,
        -Math.PI / 2,
        Math.PI / 2,
        k > 0,
      );
    }
    ctx.closePath();

    ctx.fillStyle = "#f8eed9";
    ctx.fill();
    ctx.clip();

    ctx.fillStyle = "rgba(168, 130, 74, 0.16)";
    ctx.beginPath();
    ctx.arc(-r * 0.18, -r * 0.2, r * 0.32, 0, Math.PI * 2);
    ctx.arc(r * 0.24, r * 0.16, r * 0.26, 0, Math.PI * 2);
    ctx.fill();

    ctx.restore();
  }

  function playTogoolChime() {
    if (!skySound.playing) return;
    try {
      if (!audioCtx)
        audioCtx = new (window.AudioContext || window.webkitAudioContext)();
      if (audioCtx.state === "suspended") audioCtx.resume();
      const now = audioCtx.currentTime;
      [528, 792, 1056].forEach((freq, idx) => {
        const osc = audioCtx.createOscillator();
        const gain = audioCtx.createGain();
        osc.type = idx === 0 ? "sine" : "triangle";
        osc.frequency.setValueAtTime(freq, now + idx * 0.06);
        gain.gain.setValueAtTime(0.001, now + idx * 0.06);
        gain.gain.exponentialRampToValueAtTime(
          0.08 / (idx + 1),
          now + idx * 0.06 + 0.04,
        );
        gain.gain.exponentialRampToValueAtTime(0.0001, now + idx * 0.06 + 1.2);
        osc.connect(gain);
        gain.connect(audioCtx.destination);
        osc.start(now + idx * 0.06);
        osc.stop(now + idx * 0.06 + 1.3);
      });
    } catch {
      /* Ignore */
    }
  }

