function starField() {
  let seed = 121;
  const random = () => (seed = (seed * 16807) % 2147483647) / 2147483647;
  return Array.from(
    { length: 220 },
    () =>
      `<i style="--x:${(random() * 100).toFixed(2)}%;--y:${(random() * 100).toFixed(2)}%;--s:${(0.6 + random() ** 4 * 2.6).toFixed(2)}px;--a:${(0.22 + random() * 0.65).toFixed(2)}"></i>`,
  ).join("");
}

